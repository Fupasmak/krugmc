export type IconName = keyof typeof ICONS;

export function PixelIcon({
  name,
  size = 16,
  color = 'currentColor',
  className,
}: {
  name: IconName;
  size?: number;
  color?: string;
  className?: string;
}) {
  const grid = ICONS[name];
  const side = grid.length;
  const rects: React.ReactElement[] = [];

  grid.forEach((row, y) => {
    let runStart: number | null = null;
    for (let x = 0; x <= row.length; x += 1) {
      const filled = row[x] === '1';
      if (filled && runStart === null) runStart = x;
      if (!filled && runStart !== null) {
        rects.push(
          <rect
            key={`${y}-${runStart}`}
            x={runStart}
            y={y}
            width={x - runStart}
            height={1}
            fill={color}
          />,
        );
        runStart = null;
      }
    }
  });

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${side} ${side}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {rects}
    </svg>
  );
}
